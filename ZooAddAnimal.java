    public void Search2(){
        animals.setName(searchField2.getText());

        comm.connect();
        animals = comm.getAnimal(animals);
        comm.disconnect();

        animalField.setText(animals.getName());
        descArea.setText(animals.getDescription());
      
        int JP = JOptionPane.showConfirmDialog(rootPane, "Is this what you want?");

        if (JP == JOptionPane.YES_OPTION) {
            JOptionPane.showMessageDialog(null, "Good.");
        } else {
            JOptionPane.showMessageDialog(null, "Add this animal, its probably not here...");
            reset();
        }
    }
    
    public void Search1(){
        species.setSname(searchField1.getText());

        comm.connect();
        species = comm.getSpecies(species);
        comm.disconnect();

        speciesField.setText(species.getSname());
        
      
        int JP = JOptionPane.showConfirmDialog(rootPane, "Is this what you want?");

        if (JP == JOptionPane.YES_OPTION) {
            JOptionPane.showMessageDialog(null, "Good.");
        } else {
            JOptionPane.showMessageDialog(null, "Add this species, it's not here...");
            reset();
        }
    }
    
    public void AddAnimal(){
        animals.setName(animalField.getText());
        animals.setDescription(descArea.getText());
        
        comm.connect();
        if( comm.setAnimal(animals)){
            JOptionPane.showMessageDialog(this, "Animal "+ animals.getName()+" Added");
            reset();
        }else{
            JOptionPane.showMessageDialog(this, "Error!! \nSpecies "+ animals.getName()+" Not added\nPlease try again!!!");            
        }
        comm.disconnect();

    }
    
    public void reset(){
        speciesField.setText("");
        animalField.setText("");
        descArea.setText("");
        searchField1.setText("");
        searchField2.setText("");
    }
    
    public void AddSpecies(){
        species.setSname(speciesField.getText());
        
        comm.connect();
        if( comm.setSpecies(species)){
            JOptionPane.showMessageDialog(this, "Species "+ species.getSname()+" Added");
            reset();
        }else{
            JOptionPane.showMessageDialog(this, "Error!! \nSpecies "+ species.getSname()+" Not added\nPlease try again!!!");            
        }
        comm.disconnect();

    }
    
    
    

    
