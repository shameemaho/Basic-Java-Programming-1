    public void Delete(){
        animals.setName(animalField.getText());
        animals.setDescription(descArea.getText());
        
        comm.connect();
        if( comm.removeAnimal(animals)){
            JOptionPane.showMessageDialog(this, "Animal "+ animals.getName()+" Deleted");
            reset();
        }else{
            JOptionPane.showMessageDialog(this, "Error!! \nAnimals "+ animals.getName()+" not deleted. Please try again!!!");            
        }
        comm.disconnect();
    }
    
